//! Database record models for the event_store table.
//!
//! Provides two types:
//! - `EventStoreRecord` for existing events loaded from the database
//! - `NewEventStoreRecord` for inserting new events (without id)

use chrono::{DateTime, Utc};
use diesel::QueryableByName;
use diesel::sql_types::{BigInt, Jsonb, Text, Timestamptz};
use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Database record for an existing event in the event_store table.
///
/// This type represents a complete event row including the database-generated id.
/// Supports both serde serialization and diesel raw SQL queries.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, QueryableByName)]
pub struct EventStoreRecord {
    /// Database-generated unique identifier
    #[diesel(sql_type = BigInt)]
    pub id: i64,
    /// Aggregate identifier (e.g., retailer id, order id)
    #[diesel(sql_type = Text)]
    pub agg_id: String,
    /// Sequence number for ordering events within an aggregate
    #[diesel(sql_type = BigInt)]
    pub sequence: i64,
    /// Type discriminator for the event payload (e.g., "RetailerCreated")
    #[diesel(sql_type = Text)]
    pub payload_type: String,
    /// Event payload as JSON
    #[diesel(sql_type = Jsonb)]
    pub payload: Value,
    /// Event metadata as JSON
    #[diesel(sql_type = Jsonb)]
    pub metadata: Value,
    /// Timestamp when the event was recorded
    #[diesel(sql_type = Timestamptz)]
    pub recorded_on: DateTime<Utc>,
}

/// Database record for inserting a new event into the event_store table.
///
/// This type excludes the id field since it's auto-generated by the database.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct NewEventStoreRecord {
    /// Aggregate identifier (e.g., retailer id, order id)
    pub agg_id: String,
    /// Sequence number for ordering events within an aggregate
    pub sequence: i64,
    /// Type discriminator for the event payload (e.g., "RetailerCreated")
    pub payload_type: String,
    /// Event payload as JSON
    pub payload: Value,
    /// Event metadata as JSON
    pub metadata: Value,
    /// Timestamp when the event was recorded
    pub recorded_on: DateTime<Utc>,
}

impl NewEventStoreRecord {
    /// Creates a new event record ready for insertion.
    pub fn new(
        agg_id: impl Into<String>,
        sequence: i64,
        payload_type: impl Into<String>,
        payload: Value,
        metadata: Value,
        recorded_on: DateTime<Utc>,
    ) -> Self {
        Self {
            agg_id: agg_id.into(),
            sequence,
            payload_type: payload_type.into(),
            payload,
            metadata,
            recorded_on,
        }
    }
}

impl EventStoreRecord {
    /// Creates a complete event record (typically used when loading from database).
    pub fn new(
        id: i64,
        agg_id: impl Into<String>,
        sequence: i64,
        payload_type: impl Into<String>,
        payload: Value,
        metadata: Value,
        recorded_on: DateTime<Utc>,
    ) -> Self {
        Self {
            id,
            agg_id: agg_id.into(),
            sequence,
            payload_type: payload_type.into(),
            payload,
            metadata,
            recorded_on,
        }
    }

    /// Converts to a NewEventStoreRecord by dropping the id.
    ///
    /// Useful for duplicating an event or re-inserting.
    pub fn without_id(self) -> NewEventStoreRecord {
        NewEventStoreRecord {
            agg_id: self.agg_id,
            sequence: self.sequence,
            payload_type: self.payload_type,
            payload: self.payload,
            metadata: self.metadata,
            recorded_on: self.recorded_on,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn new_event_store_record_creates_correctly() {
        let recorded = Utc::now();
        let record = NewEventStoreRecord::new(
            "agg-123",
            1,
            "TestEvent",
            json!({"field": "value"}),
            json!({"correlation_id": "corr-1"}),
            recorded,
        );

        assert_eq!(record.agg_id, "agg-123");
        assert_eq!(record.sequence, 1);
        assert_eq!(record.payload_type, "TestEvent");
        assert_eq!(record.payload, json!({"field": "value"}));
        assert_eq!(record.metadata, json!({"correlation_id": "corr-1"}));
        assert_eq!(record.recorded_on, recorded);
    }

    #[test]
    fn event_store_record_creates_correctly() {
        let recorded = Utc::now();
        let record = EventStoreRecord::new(
            42,
            "agg-456",
            5,
            "AnotherEvent",
            json!({"data": "test"}),
            json!({}),
            recorded,
        );

        assert_eq!(record.id, 42);
        assert_eq!(record.agg_id, "agg-456");
        assert_eq!(record.sequence, 5);
        assert_eq!(record.payload_type, "AnotherEvent");
        assert_eq!(record.payload, json!({"data": "test"}));
        assert_eq!(record.metadata, json!({}));
        assert_eq!(record.recorded_on, recorded);
    }

    #[test]
    fn without_id_drops_id_field() {
        let recorded = Utc::now();
        let record = EventStoreRecord::new(
            100,
            "agg-789",
            3,
            "SomeEvent",
            json!({"key": "val"}),
            json!({"user": "test"}),
            recorded,
        );

        let new_record = record.without_id();

        assert_eq!(new_record.agg_id, "agg-789");
        assert_eq!(new_record.sequence, 3);
        assert_eq!(new_record.payload_type, "SomeEvent");
        assert_eq!(new_record.payload, json!({"key": "val"}));
        assert_eq!(new_record.metadata, json!({"user": "test"}));
        assert_eq!(new_record.recorded_on, recorded);
    }

    #[test]
    fn serde_serialization_event_store_record() {
        let recorded = Utc::now();
        let record = EventStoreRecord::new(1, "agg-1", 0, "Event", json!({}), json!({}), recorded);

        let json = serde_json::to_string(&record).unwrap();
        let deserialized: EventStoreRecord = serde_json::from_str(&json).unwrap();

        assert_eq!(record, deserialized);
    }

    #[test]
    fn serde_serialization_new_event_store_record() {
        let recorded = Utc::now();
        let record = NewEventStoreRecord::new(
            "agg-2",
            1,
            "NewEvent",
            json!({"test": true}),
            json!({}),
            recorded,
        );

        let json = serde_json::to_string(&record).unwrap();
        let deserialized: NewEventStoreRecord = serde_json::from_str(&json).unwrap();

        assert_eq!(record, deserialized);
    }

    #[test]
    fn clone_works_for_both_types() {
        let recorded = Utc::now();
        let event_record = EventStoreRecord::new(1, "a", 0, "E", json!({}), json!({}), recorded);
        let new_record = NewEventStoreRecord::new("b", 1, "F", json!({}), json!({}), recorded);

        let cloned_event = event_record.clone();
        let cloned_new = new_record.clone();

        assert_eq!(event_record, cloned_event);
        assert_eq!(new_record, cloned_new);
    }
}
