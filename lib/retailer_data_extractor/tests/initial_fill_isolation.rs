    fn check(path: &Path, code: &str) {
        assert!(
            !path.is_symlink(),
            "retailer implementation must be a real file: {}",
            path.display()
        );
        if path.is_dir() {
            for entry in std::fs::read_dir(path).unwrap() {
                check(&entry.unwrap().path(), code);
            }
        } else if path.extension().is_some_and(|x| x == "rs") {
            let source = std::fs::read_to_string(path).unwrap();
            for forbidden in [
                "pub use crate::graphql_raw",
                "shopify::operations",
                "crate::nordic::raw",
                "nordic/product.graphql",
                "shopify::offer_details_v2",
                "src/shopify/operations",
                "include!(",
                "macro_rules!",
            ] {
                assert!(
                    !source.contains(forbidden),
                    "{} shares implementation through {forbidden}",
                    path.display()
                );
            }
            for line in source.lines().filter(|l| l.contains("crate::")) {
                assert!(
                    !["crate::anker", "crate::minisforum", "crate::ugreen"]
                        .iter()
                        .any(|prefix| line.contains(prefix))
                        || line.contains(&format!("crate::{code}::")),
                    "cross-retailer import in {}: {line}",
                    path.display()
                );
            }
        }
    }
    let mut count = 0;
    for retailer in RetailerCode::ALL {
        if retailer_data_extractor::initial_fill_integration_for(retailer).is_none() {
            continue;
        }
        let code = retailer.as_str();
        let brand = if code.starts_with("anker") {
            "anker"
        } else if code.starts_with("minisforum") {
            "minisforum"
        } else {
            "ugreen"
        };
        let base = root.join(format!("retailers_{brand}/src/{code}"));
        check(&base.join("initial_fill"), &code);
        check(&base.join("offer_details/v2"), &code);
        let legacy = base.join("offer_details/v1/graphql");
        if legacy.exists() {
            check(&legacy, &code);
        }
        count += 1;
    }
    assert_eq!(count, 48);
